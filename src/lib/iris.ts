export type IrisRow = {
  /** 1-based, matching how a learner would count rows in the file. */
  index: number;
  sepal_length: number;
  sepal_width: number;
  petal_length: number;
  petal_width: number;
  species: string;
};

export const IRIS: IrisRow[] = RAW.split("\n").map((line, i) => {
  const [sl, sw, pl, pw, species] = line.split(",");
  return {
    index: i + 1,
    sepal_length: Number(sl),
    sepal_width: Number(sw),
    petal_length: Number(pl),
    petal_width: Number(pw),
    species,
  };
});

const signature = (row: IrisRow) =>
  `${row.sepal_length}|${row.sepal_width}|${row.petal_length}|${row.petal_width}|${row.species}`;

/**
 * The equivalent of `df.duplicated(keep=False)` — every row that belongs to a
 * group of two or more identical rows, not just the repeats.
 */
export function identicalRowGroups(): IrisRow[][] {
  const groups = new Map<string, IrisRow[]>();
  for (const row of IRIS) {
    const key = signature(row);
    const existing = groups.get(key);
    if (existing) existing.push(row);
    else groups.set(key, [row]);
  }
  return [...groups.values()].filter((group) => group.length > 1);
}

export const IDENTICAL_GROUPS = identicalRowGroups();

export const IDENTICAL_ROW_INDICES = new Set(
  IDENTICAL_GROUPS.flat().map((row) => row.index),
);

export const DATASET_FACTS = {
  rows: IRIS.length,
  columns: CLEAN_COLUMNS.length,
  /** df.isna().sum().sum() — Iris has none, which is the point of the lesson. */
  missingValues: 0,
  identicalRowCount: IDENTICAL_ROW_INDICES.size,
  identicalGroupCount: IDENTICAL_GROUPS.length,
  species: [...new Set(IRIS.map((r) => r.species))],
  confirmedDuplicatesRemoved: 0,
} as const;

export function columnSummary(column: (typeof EXPECTED_NUMERIC_COLUMNS)[number]) {
  const values = IRIS.map((row) => row[column] as number).sort((a, b) => a - b);
  const mean = values.reduce((sum, v) => sum + v, 0) / values.length;
  const mid = Math.floor(values.length / 2);
  const median =
    values.length % 2 === 0 ? (values[mid - 1] + values[mid]) / 2 : values[mid];
  return {
    column,
    min: values[0],
    max: values[values.length - 1],
    mean: Number(mean.toFixed(3)),
    median: Number(median.toFixed(3)),
    missing: 0,
    dtype: "float64",
  };
}

export const NUMERIC_SUMMARY = EXPECTED_NUMERIC_COLUMNS.map((c) =>
  columnSummary(c as (typeof EXPECTED_NUMERIC_COLUMNS)[number]),
);

/** The column-name rule taught in DS-L03, applied literally. */
export function standardizeColumnName(name: string): string {
  return name.trim().toLowerCase().replace(/ /g, "_").replace(/\(/g, "").replace(/\)/g, "");
}
